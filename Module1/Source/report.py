"""Module 1 -- the "ship / serve / expose" step (MASTER plan 5.13).

Writes:
  report/budget.md    -- the by-hand numbers (Examples E6, E7, refresh table)
                         plus the per-image / set totals for data/
  report/report.html  -- budget table + histogram + the naive/correct/diff
                         downscale triptych + a CVD before/after, all images
                         inline (base64), so the marker opens ONE file.

Run:  python report.py            # expects `make data` + downscale artifacts
"""
from __future__ import annotations

import base64
import io
import os

import numpy as np

from ppm_io import read_ppm
import budget as B


def _png_data_uri(img: np.ndarray) -> str:
    """PNG via Pillow if present, else a raw PPM data URI (browsers won't show
    PPM, so fall back to a note)."""
    try:
        from PIL import Image
        buf = io.BytesIO()
        if img.ndim == 2:
            Image.fromarray(img, "L").save(buf, format="PNG")
        else:
            Image.fromarray(img, "RGB").save(buf, format="PNG")
        return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
    except Exception:
        return ""


def _img_tag(path: str, alt: str) -> str:
    if not os.path.exists(path):
        return f'<p><em>missing: {path}</em></p>'
    uri = _png_data_uri(read_ppm(path))
    if not uri:
        return f'<p><em>{alt}: {path} (install Pillow to inline this image)</em></p>'
    return f'<figure><img src="{uri}" alt="{alt}"><figcaption>{alt}</figcaption></figure>'


def build_budget_md(out: str) -> None:
    lines = ["# Module 1 -- budget.md\n",
             "Regenerated by `python report.py`. Numbers below are the",
             "canonical Examples E6/E7 plus the committed data/ set.\n",
             "```"]
    import contextlib
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        B.canonical()
        print()
        if os.path.isdir("data"):
            B.from_set("data")
    lines.append(buf.getvalue())
    lines.append("```\n")
    with open(os.path.join(out, "budget.md"), "w") as f:
        f.write("\n".join(lines))


def build_html(out: str) -> None:
    css = ("body{font:14px/1.5 system-ui,sans-serif;max-width:900px;margin:2rem auto;"
           "padding:0 1rem;color:#123} h1,h2{color:#036} "
           "figure{display:inline-block;margin:.5rem;text-align:center} "
           "img{image-rendering:pixelated;border:1px solid #ccc;max-width:256px} "
           "pre{background:#f0f4f8;padding:1rem;overflow-x:auto} "
           "figcaption{font-size:12px;color:#555}")
    parts = [f"<!doctype html><meta charset=utf-8><title>Pusaka3D Module 1 report</title>",
             f"<style>{css}</style>",
             "<h1>Pusaka3D &mdash; Module 1: Digital Representation, Colour &amp; Memory</h1>",
             "<h2>Budget</h2><pre>"]
    import contextlib
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        B.canonical()
        print()
        if os.path.isdir("data"):
            B.from_set("data")
    parts.append(buf.getvalue().replace("&", "&amp;").replace("<", "&lt;"))
    parts.append("</pre>")

    parts.append("<h2>Downscale: naive (sRGB space) vs linear-correct vs difference &times;4</h2>")
    parts.append(_img_tag("report/relief_naive.ppm", "naive 2x (sRGB-space box average)"))
    parts.append(_img_tag("report/relief_linear.ppm", "linear-correct 2x (decode, average, encode)"))
    parts.append(_img_tag("report/relief_diff.ppm", "|difference| x4  (bright = the gamma error)"))

    parts.append("<h2>Source images (a sample)</h2>")
    for name in ("relief.ppm", "silhouette.pgm", "gradient.ppm", "gradient5.pgm"):
        parts.append(_img_tag(os.path.join("data", name), name))

    parts.append("<h2>CVD check &mdash; a viridis luminance-ramp legend "
                 "(survives deuteranopia, protanopia, and grayscale)</h2>")
    try:
        import cvd
        good = [(68, 1, 84), (59, 82, 139), (33, 145, 140), (94, 201, 98), (253, 231, 37)]
        row = cvd._swatches(good)
        for label, im in (("normal vision", row),
                          ("deuteranopia sim", cvd.simulate(row, "deuteranopia")),
                          ("protanopia sim", cvd.simulate(row, "protanopia")),
                          ("grayscale test", cvd.grayscale_test(row))):
            uri = _png_data_uri(im)
            if uri:
                parts.append(f'<figure><img src="{uri}" alt="{label}">'
                             f'<figcaption>{label}</figcaption></figure>')
    except Exception as e:
        parts.append(f"<p><em>CVD panel skipped: {e}</em></p>")

    with open(os.path.join(out, "report.html"), "w", encoding="utf-8") as f:
        f.write("\n".join(parts))


def main() -> None:
    out = "report"
    os.makedirs(out, exist_ok=True)
    build_budget_md(out)
    build_html(out)
    print(f"wrote {out}/budget.md and {out}/report.html")


if __name__ == "__main__":
    main()
